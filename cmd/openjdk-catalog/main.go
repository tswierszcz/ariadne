// Command openjdk-catalog converts OpenJDK Vulnerability Group advisory
// pages, saved by hand from a browser as YYYY-MM-DD.html, into the curated
// catalog ariadne embeds (internal/runtimevuln/openjdk_advisories.yaml).
// It reads local files only: ariadne never fetches openjdk.org, whose terms
// of use do not allow automated access. The output is a draft to check
// against the pages before committing it.
//
// Usage: go run ./cmd/openjdk-catalog -version N DIR > internal/runtimevuln/openjdk_advisories.yaml
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"ariadne/internal/runtimevuln"

	"gopkg.in/yaml.v3"
)

var nameRe = regexp.MustCompile(`^(\d{4}-\d{2}-\d{2})\.html?$`)

func main() {
	version := flag.String("version", "", "catalog version to write (required; bump it on every change)")
	flag.Parse()
	if *version == "" || flag.NArg() != 1 {
		fmt.Fprintln(os.Stderr, "usage: openjdk-catalog -version N DIR")
		os.Exit(2)
	}
	if err := run(*version, flag.Arg(0)); err != nil {
		fmt.Fprintln(os.Stderr, "openjdk-catalog:", err)
		os.Exit(1)
	}
}

func run(version, dir string) error {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return err
	}
	c := runtimevuln.Catalog{Schema: 1, Version: version, Source: "OpenJDK Vulnerability Group advisories (curated by hand)",
		Note: "converted from pages saved by hand; checked against the pages"}
	var errs []string
	for _, e := range entries {
		m := nameRe.FindStringSubmatch(e.Name())
		if m == nil {
			continue
		}
		b, err := os.ReadFile(filepath.Join(dir, e.Name()))
		if err != nil {
			return err
		}
		a, err := runtimevuln.ParseAdvisoryHTML(m[1], string(b))
		if err != nil {
			errs = append(errs, err.Error())
			continue
		}
		c.Advisories = append(c.Advisories, a)
	}
	if len(errs) > 0 {
		return fmt.Errorf("%d page(s) not converted:\n  %s", len(errs), strings.Join(errs, "\n  "))
	}
	if len(c.Advisories) == 0 {
		return fmt.Errorf("no YYYY-MM-DD.html pages in %s", dir)
	}
	sort.Slice(c.Advisories, func(i, j int) bool { return c.Advisories[i].Date < c.Advisories[j].Date })
	out, err := yaml.Marshal(c)
	if err != nil {
		return err
	}
	// The catalog must round-trip through the loader's own validation.
	if _, err := runtimevuln.ParseCatalog(out); err != nil {
		return err
	}
	_, err = os.Stdout.Write(append([]byte(header), out...))
	return err
}

const header = `# Curated catalog of the OpenJDK Vulnerability Group's advisories
# (https://openjdk.org/groups/vulnerability/advisories/), CVE:F8b.
# Generated by cmd/openjdk-catalog from pages saved by hand; ariadne never
# fetches openjdk.org (its terms of use do not allow automated access).
# Check every entry against its page before committing. Format: see
# internal/runtimevuln/runtimevuln.go (Catalog).
`
