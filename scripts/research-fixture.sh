#!/usr/bin/env bash
# RESEARCH_INTERFACE RI1-RI3/RI5: builds the research control library under
# testdata/research (see EXPECTED.MD there):
#   lib.jar            fx.research.* (the analysed library)
#   deps/fx-dep-1.0.jar  fx.dep.Paths2 version 1 (selected: ariadne lists a
#                      dependency directory by file name, first copy wins)
#   deps/fx-dep-2.0.jar  fx.dep.Paths2 version 2 (shadowed copy)
#   client.jar         fx.client.Main, public API calls only (the oracle)
# then runs the client under scripts/MethodTrace.java (JDI) and writes every
# fx.* body the JVM entered to testdata/research/observed.txt.
# Jars and observed.txt are committed; the Go tests need no JDK.
#
# Usage: scripts/research-fixture.sh [JAVA_HOME]
set -euo pipefail
JAVA_HOME_ARG="${1:-${JAVA_HOME:-}}"
if [ -n "$JAVA_HOME_ARG" ]; then
    export JAVA_HOME="$JAVA_HOME_ARG"
    export PATH="$JAVA_HOME/bin:$PATH"
fi
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
fx="$root/testdata/research"
mkdir -p "$fx/deps"
java "$root/scripts/JavaBuild.java" "$fx/dep" "$fx/deps/fx-dep-2.0.jar" 11
java "$root/scripts/JavaBuild.java" "$fx/depold" "$fx/deps/fx-dep-1.0.jar" 11
java "$root/scripts/JavaBuild.java" "$fx/lib" "$fx/lib.jar" 11 "$fx/deps/fx-dep-2.0.jar"
java "$root/scripts/JavaBuild.java" "$fx/client" "$fx/client.jar" 11 "$fx/lib.jar"
printf 'fx.test:fx-dep:jar:1.0:compile\nfx.test:fx-dep:jar:2.0:compile\n' > "$fx/deps.txt"
cp_list="$fx/client.jar:$fx/lib.jar:$fx/deps/fx-dep-1.0.jar:$fx/deps/fx-dep-2.0.jar"  # the order ariadne selects in
java "$root/scripts/MethodTrace.java" "$cp_list" fx.client.Main "$fx/observed.raw" 'fx.research.*' 'fx.dep.*'
{
    echo "# generated by scripts/research-fixture.sh on $(java -version 2>&1 | head -1)"
    echo "# fx.research.* and fx.dep.* method bodies that ran on the real JVM (owner#name+desc)"
    grep -v '\$\$Lambda/' "$fx/observed.raw"
} > "$fx/observed.txt"
rm "$fx/observed.raw"
cat "$fx/observed.txt"
