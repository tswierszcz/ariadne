#!/usr/bin/env bash
# Spring ORM JPA proxy (framework:proxies spring-orm:*) oracle (ROADMAP B4).
# Builds testdata/jpa:
#   deps/*.jar  the real Spring Framework 5.3.6 jars and the JPA 2.2 API
#               (jakarta.persistence-api 2.2.3, javax.persistence packages)
#               — Apache 2.0 and EPL 2.0/EDL 1.0 — copied without
#               META-INF/maven so the offline test makes no OSV query
#               (classes byte-identical; the originals' SHA-256 in
#               deps/ORIGINALS.sha256)
#   app.jar     fx.app.Main: the shared entity manager, its deferred query
#               and the managed entity manager factory with its extended
#               entity managers, over a minimal provider (fx.store: an
#               EntityManagerFactory, EntityManager and Query whose bodies
#               record every frame on the stack) instead of Hibernate
# and runs Main on the real JVM. Writes testdata/jpa/observed.txt.
# The jars and the file are committed; TestJPAOracle needs no JDK.
#
# Usage: scripts/jpa-oracle.sh [JAVA_HOME] (the jars are read from
# work/spring-petclinic/target/dependency, scripts/prepare-petclinic.sh)
set -euo pipefail
JAVA_HOME_ARG="${1:-${JAVA_HOME:-}}"
if [ -n "$JAVA_HOME_ARG" ]; then
    export JAVA_HOME="$JAVA_HOME_ARG"
    export PATH="$JAVA_HOME/bin:$PATH"
fi
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
fx="$root/testdata/jpa"
src="$root/work/spring-petclinic/target/dependency"
JARS="spring-jcl-5.3.6 spring-core-5.3.6 spring-beans-5.3.6 spring-tx-5.3.6 spring-orm-5.3.6 jakarta.persistence-api-2.2.3"
mkdir -p "$fx/deps"
: > "$fx/deps/ORIGINALS.sha256.new"
cp_jar() { # name
    local orig="$src/$1.jar" dst="$fx/deps/$1.jar"
    printf '%s  %s.jar\n' "$(sha256sum "$orig" | cut -d' ' -f1)" "$1" >> "$fx/deps/ORIGINALS.sha256.new"
    [ -f "$dst" ] && return
    python3 -I - "$orig" "$dst" <<'PY'
import sys, zipfile
src, dst = sys.argv[1], sys.argv[2]
with zipfile.ZipFile(src) as zi, zipfile.ZipFile(dst, "w", zipfile.ZIP_DEFLATED) as zo:
    for info in zi.infolist():
        if not info.filename.startswith("META-INF/maven/"):
            zo.writestr(info, zi.read(info))
PY
}
cp_list=""
for j in $JARS; do cp_jar "$j"; cp_list="$cp_list:$fx/deps/$j.jar"; done
mv "$fx/deps/ORIGINALS.sha256.new" "$fx/deps/ORIGINALS.sha256"
cp_list="${cp_list#:}"
java "$root/scripts/JavaBuild.java" "$fx/app" "$fx/app.jar" 17 "$cp_list"
{
    echo "# generated by scripts/jpa-oracle.sh on $(java -version 2>&1 | head -1)"
    java -cp "$fx/app.jar:$cp_list" fx.app.Main
} > "$fx/observed.txt"
grep -c . "$fx/observed.txt"
