#!/usr/bin/env bash
# REFLECTION R3 oracle (r3-3): Method objects passed as parameters.
# Builds testdata/reflectparam/app.jar from app/ (no dependencies) and runs
# fx.app.Main on the real JVM; each invoked target records the whole stack.
# Writes testdata/reflectparam/observed.txt. The jar and the file are
# committed; TestReflectParamOracle needs no JDK.
#
# Usage: scripts/reflectparam-oracle.sh [JAVA_HOME]
set -euo pipefail
JAVA_HOME_ARG="${1:-${JAVA_HOME:-}}"
if [ -n "$JAVA_HOME_ARG" ]; then
    export JAVA_HOME="$JAVA_HOME_ARG"
    export PATH="$JAVA_HOME/bin:$PATH"
fi
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
fx="$root/testdata/reflectparam"
java "$root/scripts/JavaBuild.java" "$fx/app" "$fx/app.jar" 11
{
    echo "# generated by scripts/reflectparam-oracle.sh on $(java -version 2>&1 | head -1)"
    java -cp "$fx/app.jar" fx.app.Main
} > "$fx/observed.txt"
grep -c . "$fx/observed.txt"
