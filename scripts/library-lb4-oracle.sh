#!/usr/bin/env bash
# LIBRARY_MODE LB4 oracle for the callback-style library of the
# qualification set (testdata/library-lb4/EXPECTED.MD): builds
# testdata/library-lb4/jetty-client/client.jar (fx.JettyGet: a library user
# that calls only HttpClient#start, #GET and #stop against a local socket
# answering "Content-Length: +5") against the committed jetty-client
# 9.4.36 jars, runs it under scripts/MethodTrace.java (JDI) and writes to
# observed.txt every org.eclipse.jetty.client body the JVM entered plus the
# two mapped vulnerable methods (lambda hidden classes, whose names vary per
# run, left out) (HttpParser#convertContentLength,
# CVE-2023-40167; HttpURI#parse(State,…), CVE-2022-2047). Needs no network.
# The jar and the file are committed; the Go tests need no JDK.
#
# Usage: scripts/library-lb4-oracle.sh
set -euo pipefail
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
fx="$root/testdata/library-lb4/jetty-client"
cp="$fx/lib.jar"
for j in "$fx"/deps/*.jar; do cp="$cp:$j"; done
java "$root/scripts/JavaBuild.java" "$fx/client" "$fx/client.jar" 11 "$cp"
java "$root/scripts/MethodTrace.java" "$fx/client.jar:$cp" fx.JettyGet "$fx/observed.raw" 'org.eclipse.jetty.*'
{
    echo "# generated by scripts/library-lb4-oracle.sh on $(java -version 2>&1 | head -1) with jetty-client 9.4.36.v20210114"
    echo "# org.eclipse.jetty.client bodies and the mapped vulnerable methods that ran on the real JVM (owner#name+desc)"
    grep -E '^org\.eclipse\.jetty\.client\.|^org\.eclipse\.jetty\.http\.HttpParser#convertContentLength|^org\.eclipse\.jetty\.http\.HttpURI#parse\(Lorg' "$fx/observed.raw" | grep -v '\$\$Lambda' | sort -u
} > "$fx/observed.txt"
rm "$fx/observed.raw"
grep -c '#' "$fx/observed.txt"
