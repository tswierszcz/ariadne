#!/usr/bin/env bash
# Spring application events oracle (spring:events).
# Builds testdata/events/app.jar against the Spring Framework 5.3.6 jars
# testdata/tx already holds (scripts/tx-oracle.sh; no copy here):
#   fx.app.Main publishes a payload event, one inside a transaction and an
#   ApplicationEvent through services, and waits for @Scheduled methods
#   (one repeated, so its class file holds @Schedules). Listeners: an
#   @EventListener on the exact type, on a supertype, with classes= and no
#   parameter (a container event), on a @Bean-registered class, a
#   @TransactionalEventListener, an ApplicationListener, and two that never
#   run (an event type nothing publishes; a class that is not a bean).
# and runs Main on the real JVM. Writes testdata/events/observed.txt.
# The jar and the file are committed; TestEventsOracle needs no JDK.
#
# Usage: scripts/events-oracle.sh [JAVA_HOME]
set -euo pipefail
JAVA_HOME_ARG="${1:-${JAVA_HOME:-}}"
if [ -n "$JAVA_HOME_ARG" ]; then
    export JAVA_HOME="$JAVA_HOME_ARG"
    export PATH="$JAVA_HOME/bin:$PATH"
fi
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
fx="$root/testdata/events"
deps="$root/testdata/tx/deps"
cp_list=""
for j in spring-jcl spring-core spring-beans spring-aop spring-context spring-expression spring-tx; do
    cp_list="$cp_list:$deps/$j-5.3.6.jar"
done
cp_list="${cp_list#:}"
java "$root/scripts/JavaBuild.java" "$fx/app" "$fx/app.jar" 11 "$cp_list"
{
    echo "# generated by scripts/events-oracle.sh on $(java -version 2>&1 | head -1)"
    java -cp "$fx/app.jar:$cp_list" fx.app.Main
} > "$fx/observed.txt"
grep -c . "$fx/observed.txt"
