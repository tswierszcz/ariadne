#!/usr/bin/env bash
# Regenerates internal/mavenversion's reference data (CVE:F4) from the
# installed Maven's own ComparableVersion / VersionRange: the version order
# (maven-<v>-order.tsv), range decisions (maven-<v>-ranges.tsv) and token
# structures (maven-<v>-tokens.txt). Needs a
# Java runtime with jdk.compiler (single-file source launch) and `mvn`.
set -euo pipefail
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
td="$root/internal/mavenversion/testdata"
lib="$(dirname "$(readlink -f "$(command -v mvn)")")/../lib"
jar="$(ls "$lib"/maven-artifact-*.jar | head -1)"
mv="$(mvn -B -v | sed 's/\x1b\[[0-9;]*m//g' | sed -n 's/^Apache Maven \([0-9.]*\).*/\1/p' | head -1)"
{
    echo "# Versions in the order Maven $mv's ComparableVersion sorts them (the installed mvn's"
    echo "# maven-artifact jar); equal versions share a rank. Generated by"
    echo "# scripts/maven-version-oracle.sh (testdata/oracle/Order.java)."
    java -cp "$jar" "$td/oracle/Order.java" "$td/oracle/versions.txt"
} > "$td/maven-$mv-order.tsv"
java -cp "$jar" "$td/oracle/Ranges.java" > "$td/maven-$mv-ranges.tsv"
# shellcheck disable=SC2046
java -cp "$jar" org.apache.maven.artifact.versioning.ComparableVersion $(grep -v '^#' "$td/oracle/versions.txt") \
    | grep -- ' -> ' | sed -E 's/^[0-9]+\. //' > "$td/maven-$mv-tokens.txt"
echo "wrote $td/maven-$mv-{order,ranges}.tsv and maven-$mv-tokens.txt"
