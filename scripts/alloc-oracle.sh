#!/usr/bin/env bash
# GRAPH_PRECISION P1 created-type oracle. Compiles testdata/alloc/src
# (objects created with `new`, in a factory, by reflection with a literal
# class name, as a ServiceLoader provider, by deserialization, as a
# dynamic proxy and a lambda; one class allocated only in a method nothing
# calls; one abstract class) into testdata/alloc/alloc.jar with the real
# javac, adds META-INF/services, and runs al.Oracle on the real JVM, which
# prints the runtime class of every object the fixture created.
# Writes testdata/alloc/observed.txt; the jar and the file are committed,
# and internal/alloc TestCreatedTypesOracle checks the catalog against them
# without a JDK. A class not observed is not proven never created: only
# this run was observed.
#
# Usage: scripts/alloc-oracle.sh [JAVA_HOME]
set -euo pipefail
JAVA_HOME_ARG="${1:-${JAVA_HOME:-}}"
if [ -n "$JAVA_HOME_ARG" ]; then
    export JAVA_HOME="$JAVA_HOME_ARG"
    export PATH="$JAVA_HOME/bin:$PATH"
fi
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
fx="$root/testdata/alloc"
java "$root/scripts/JavaBuild.java" "$fx/src" "$fx/alloc.jar" 17
# add the provider registration (JavaBuild jars compiled classes only)
cat > "$fx/.AddResources.java" <<'J'
import java.util.spi.ToolProvider;
public class AddResources {
    public static void main(String[] a) {
        System.exit(ToolProvider.findFirst("jar").orElseThrow().run(System.out, System.err,
            "--update", "--file", a[0], "--date", "2026-01-01T00:00:00Z", "-C", a[1], "."));
    }
}
J
java "$fx/.AddResources.java" "$fx/alloc.jar" "$fx/resources"
rm -f "$fx/.AddResources.java"
{
    echo "# generated by scripts/alloc-oracle.sh on $(java -version 2>&1 | head -1)"
    java -cp "$fx/alloc.jar" al.Oracle
} > "$fx/observed.txt"
cat "$fx/observed.txt"
