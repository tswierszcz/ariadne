#!/usr/bin/env bash
# Library mode autoconfiguration oracle (LIBRARY_MODE LB2). Builds
# testdata/library-autoconfig/lib.jar (the control starter: cases (j)-(o),
# see its EXPECTED.MD) against commons-text 1.9 and Spring Boot 2.4.5, and
# client.jar (fx.Main: a Spring Boot application with
# @EnableAutoConfiguration), then runs the client under
# scripts/MethodTrace.java (JDI) and writes every ac.* body and
# StringSubstitutor#replace the JVM entered to observed.txt. Spring is
# provided: its jars are read from work/spring-petclinic/target/dependency
# (scripts/prepare-petclinic.sh) and never committed; the analysis
# dependencies are testdata/library/deps. The jars and the file are
# committed; the Go tests need no JDK.
#
# Usage: scripts/library-autoconfig-oracle.sh [JAVA_HOME]
set -euo pipefail
JAVA_HOME_ARG="${1:-${JAVA_HOME:-}}"
if [ -n "$JAVA_HOME_ARG" ]; then
    export JAVA_HOME="$JAVA_HOME_ARG"
    export PATH="$JAVA_HOME/bin:$PATH"
fi
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
fx="$root/testdata/library-autoconfig"
deps="$root/testdata/library/deps"
spring="$root/work/spring-petclinic/target/dependency"
sp=""
for j in spring-boot-2.4.5 spring-boot-autoconfigure-2.4.5 spring-context-5.3.6 spring-core-5.3.6 spring-beans-5.3.6 \
         spring-aop-5.3.6 spring-expression-5.3.6 spring-jcl-5.3.6 jakarta.annotation-api-1.3.5 snakeyaml-1.27; do
    sp="$sp:$spring/$j.jar"
done
sp="${sp#:}"
text="$deps/commons-text-1.9.jar:$deps/commons-lang3-3.11.jar"
java "$root/scripts/JavaBuild.java" "$fx/lib" "$fx/lib.jar" 11 "$text:$sp"
java "$root/scripts/JavaBuild.java" "$fx/client" "$fx/client.jar" 11 "$sp"
java "$root/scripts/MethodTrace.java" "$fx/client.jar:$fx/lib.jar:$text:$sp" fx.Main "$fx/observed.raw" 'ac.*' 'org.apache.commons.text.StringSubstitutor'
{
    echo "# generated by scripts/library-autoconfig-oracle.sh on $(java -version 2>&1 | head -1)"
    echo "# ac.* and StringSubstitutor method bodies that ran on the real JVM (owner#name+desc)"
    grep -v '\$\$Lambda/' "$fx/observed.raw" | grep -E '^ac\.|#replace\('
} > "$fx/observed.txt"
rm "$fx/observed.raw"
cat "$fx/observed.txt"
