#!/usr/bin/env bash
# Service-provider dispatch oracle (model service-provider:dispatch).
# Compiles testdata/spidispatch into four jars — api.jar (a javax.* SPI the
# call graph never CHA-expands: spi.CodecProvider, its product Codec, the
# bootstrap Codecs), provider.jar (the registered Base64Provider with
# Base64Codec, and an UnusedCodec never created), other.jar (RogueCodec and
# an unregistered RogueProvider), app.jar (fx.app.Main) — and runs Main on
# the real JVM, which prints every method body that ran. Writes
# testdata/spidispatch/observed.txt; the jars and the file are committed and
# cmd/ariadne TestSPIDispatchOracle checks the graph against them without a
# JDK.
#
# Usage: scripts/spidispatch-oracle.sh [JAVA_HOME]
set -euo pipefail
JAVA_HOME_ARG="${1:-${JAVA_HOME:-}}"
if [ -n "$JAVA_HOME_ARG" ]; then
    export JAVA_HOME="$JAVA_HOME_ARG"
    export PATH="$JAVA_HOME/bin:$PATH"
fi
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
fx="$root/testdata/spidispatch"
mkdir -p "$fx/deps"
java "$root/scripts/JavaBuild.java" "$fx/api" "$fx/deps/api.jar" 17
java "$root/scripts/JavaBuild.java" "$fx/provider" "$fx/deps/provider.jar" 17 "$fx/deps/api.jar"
java "$root/scripts/JavaBuild.java" "$fx/other" "$fx/deps/other.jar" 17 "$fx/deps/api.jar"
java "$root/scripts/JavaBuild.java" "$fx/app" "$fx/app.jar" 17 "$fx/deps/api.jar"
cat > "$fx/.AddResources.java" <<'J'
import java.util.spi.ToolProvider;
public class AddResources {
    public static void main(String[] a) {
        System.exit(ToolProvider.findFirst("jar").orElseThrow().run(System.out, System.err,
            "--update", "--file", a[0], "--date", "2026-01-01T00:00:00Z", "-C", a[1], "."));
    }
}
J
java "$fx/.AddResources.java" "$fx/deps/provider.jar" "$fx/provider-resources"
rm -f "$fx/.AddResources.java"
{
    echo "# generated by scripts/spidispatch-oracle.sh on $(java -version 2>&1 | head -1)"
    java -cp "$fx/app.jar:$fx/deps/api.jar:$fx/deps/provider.jar:$fx/deps/other.jar" fx.app.Main
} > "$fx/observed.txt"
cat "$fx/observed.txt"
