#!/usr/bin/env bash
# RESEARCH_HARNESS RH-A3: builds the pilot control target under
# testdata/pilot (see EXPECTED.MD there): the same public API in two
# variants that differ only in px.archive.Entries,
#   defective.jar  resolves a zip entry name as given (writes outside dest)
#   fixed.jar      refuses a name that resolves outside dest
#   client.jar     px.client.Main, public API calls only (the oracle)
# then runs the client on each variant under scripts/MethodTrace.java (JDI)
# and writes every px.* body the JVM entered to observed-VARIANT.txt and
# the client's file-system observations to effects-VARIANT.txt.
# Jars and the observation files are committed; the Go tests need no JDK.
#
# Usage: scripts/pilot-fixture.sh [JAVA_HOME]
set -euo pipefail
JAVA_HOME_ARG="${1:-${JAVA_HOME:-}}"
if [ -n "$JAVA_HOME_ARG" ]; then
    export JAVA_HOME="$JAVA_HOME_ARG"
    export PATH="$JAVA_HOME/bin:$PATH"
fi
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
fx="$root/testdata/pilot"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
for v in defective fixed; do
    mkdir -p "$tmp/$v"
    cp -r "$fx/common/." "$tmp/$v/"
    cp -r "$fx/$v/." "$tmp/$v/"
    java "$root/scripts/JavaBuild.java" "$tmp/$v" "$fx/$v.jar" 11
done
java "$root/scripts/JavaBuild.java" "$fx/client" "$fx/client.jar" 11 "$fx/defective.jar"
for v in defective fixed; do
    java "$root/scripts/MethodTrace.java" "$fx/client.jar:$fx/$v.jar" px.client.Main "$tmp/observed.raw" 'px.archive.*' > "$tmp/stdout"
    {
        echo "# generated by scripts/pilot-fixture.sh on $(java -version 2>&1 | head -1)"
        echo "# px.archive.* method bodies that ran on the real JVM with $v.jar (owner#name+desc)"
        cat "$tmp/observed.raw"
    } > "$fx/observed-$v.txt"
    {
        echo "# generated by scripts/pilot-fixture.sh: the client's file-system observations with $v.jar"
        grep '^effect: ' "$tmp/stdout"
    } > "$fx/effects-$v.txt"
done
cat "$fx"/effects-*.txt
