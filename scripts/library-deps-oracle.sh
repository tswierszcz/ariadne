#!/usr/bin/env bash
# Library dependency oracle (LIBRARY_MODE LB3). Builds
# testdata/library-deps/lib.jar (the control library, see its EXPECTED.MD)
# and asks real Maven what a consumer of the library gets: the jar and its
# pom go into a file repository under work/, a consumer pom depends on
# fx:library-deps:1.0, and `mvn dependency:list` (runtime classpath, the
# library itself left out) is written to
# testdata/library-deps/maven-consumer.txt. ariadne's supplied_by=library
# set must equal that list. The jar and the file are committed; the Go
# tests need neither Maven nor a JDK.
#
# Usage: scripts/library-deps-oracle.sh
set -euo pipefail
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
fx="$root/testdata/library-deps"
deps="$root/testdata/library/deps"
java "$root/scripts/JavaBuild.java" "$fx/lib" "$fx/lib.jar" 11 "$deps/commons-text-1.9.jar:$deps/commons-lang3-3.11.jar"

work="$root/work/library-deps-oracle"
rm -rf "$work"
repo="$work/repo/fx/library-deps/1.0"
mkdir -p "$repo" "$work/consumer"
cp "$fx/lib.jar" "$repo/library-deps-1.0.jar"
cp "$fx/lib/META-INF/maven/fx/library-deps/pom.xml" "$repo/library-deps-1.0.pom"
cat >"$work/consumer/pom.xml" <<POM
<project xmlns="http://maven.apache.org/POM/4.0.0"><modelVersion>4.0.0</modelVersion>
<groupId>oracle</groupId><artifactId>consumer</artifactId><version>1</version>
<repositories><repository><id>fx</id><url>file://$work/repo</url></repository></repositories>
<dependencies><dependency><groupId>fx</groupId><artifactId>library-deps</artifactId><version>1.0</version></dependency></dependencies></project>
POM
(cd "$work/consumer" && mvn -q -B -Dstyle.color=never dependency:list -DincludeScope=runtime -DexcludeArtifactIds=library-deps -DoutputFile=list.txt -DoutputAbsoluteArtifactFilename=false)
# Maven caches the fixture artifact in the local repository; drop it.
rm -rf "${HOME}/.m2/repository/fx/library-deps"
{
    echo "# generated by scripts/library-deps-oracle.sh with $(mvn -B -v 2>/dev/null | head -1 | sed -E "s/\x1b\\[[0-9;]*m//g")"
    echo "# what a consumer of fx:library-deps:1.0 gets on its runtime classpath (group:artifact:version:scope)"
    grep -E '^\s+[^ ]+:[^ ]+:jar:' "$work/consumer/list.txt" | sed -E 's/^\s+//; s/:jar:/:/; s/ .*//' | sort
} >"$fx/maven-consumer.txt"
cat "$fx/maven-consumer.txt"
