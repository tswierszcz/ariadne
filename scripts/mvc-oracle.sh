#!/usr/bin/env bash
# Spring MVC oracle (FRAMEWORKS F5 f5-2): the container before the
# controller. Builds testdata/mvc:
#   deps/*.jar  the real spring-web/spring-webmvc 5.3.6, embedded Tomcat
#               9.0.45 with the JSR-250 API it needs (jakarta.annotation-api
#               1.3.5, javax.annotation packages) and Jackson 2.11.4 (Apache
#               2.0; Tomcat Apache 2.0, annotation API EPL 2.0/GPL-2.0-with-CPE;
#               Tomcat with CDDL/EPL parts), copied without META-INF/maven so the
#               offline test makes no OSV query (classes byte-identical;
#               the originals' SHA-256 in deps/ORIGINALS.sha256). The other
#               Spring Framework 5.3.6 jars come from testdata/tx/deps
#               (scripts/tx-oracle.sh; no copy here).
#   app.jar     fx.app.Main starts a real embedded Tomcat with a
#               DispatcherServlet over an @EnableWebMvc context and sends
#               real HTTP requests: a plain mapping, a path variable through
#               a registered Converter with a Jackson-written result, a
#               Jackson-read @RequestBody, a handler whose exception a
#               @RestControllerAdvice answers, an interceptor, a
#               @ModelAttribute and an @InitBinder method; negatives: an
#               unmapped public method and a controller outside the
#               component scan (its request is a 404)
# and runs Main on the real JVM. Writes testdata/mvc/observed.txt.
# The jars and the file are committed; TestMVCOracle needs no JDK.
#
# Usage: scripts/mvc-oracle.sh [JAVA_HOME] (the jars are read from
# work/spring-petclinic/target/dependency, scripts/prepare-petclinic.sh)
set -euo pipefail
JAVA_HOME_ARG="${1:-${JAVA_HOME:-}}"
if [ -n "$JAVA_HOME_ARG" ]; then
    export JAVA_HOME="$JAVA_HOME_ARG"
    export PATH="$JAVA_HOME/bin:$PATH"
fi
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
fx="$root/testdata/mvc"
src="$root/work/spring-petclinic/target/dependency"
JARS="spring-web-5.3.6 spring-webmvc-5.3.6 tomcat-embed-core-9.0.45 jakarta.annotation-api-1.3.5 jackson-databind-2.11.4 jackson-core-2.11.4 jackson-annotations-2.11.4"
mkdir -p "$fx/deps"
: > "$fx/deps/ORIGINALS.sha256.new"
cp_jar() { # name
    local orig="$src/$1.jar" dst="$fx/deps/$1.jar"
    printf '%s  %s.jar\n' "$(sha256sum "$orig" | cut -d' ' -f1)" "$1" >> "$fx/deps/ORIGINALS.sha256.new"
    [ -f "$dst" ] && return
    python3 -I - "$orig" "$dst" <<'PY'
import sys, zipfile
src, dst = sys.argv[1], sys.argv[2]
with zipfile.ZipFile(src) as zi, zipfile.ZipFile(dst, "w", zipfile.ZIP_DEFLATED) as zo:
    for info in zi.infolist():
        if not info.filename.startswith("META-INF/maven/"):
            zo.writestr(info, zi.read(info))
PY
}
cp_list=""
for j in $JARS; do cp_jar "$j"; cp_list="$cp_list:$fx/deps/$j.jar"; done
mv "$fx/deps/ORIGINALS.sha256.new" "$fx/deps/ORIGINALS.sha256"
for j in "$root"/testdata/tx/deps/spring-{jcl,core,beans,aop,context,expression}-5.3.6.jar; do cp_list="$cp_list:$j"; done
cp_list="${cp_list#:}"
java "$root/scripts/JavaBuild.java" "$fx/app" "$fx/app.jar" 11 "$cp_list"
{
    echo "# generated by scripts/mvc-oracle.sh on $(java -version 2>&1 | head -1)"
    java -cp "$fx/app.jar:$cp_list" fx.app.Main 2>/dev/null
} > "$fx/observed.txt"
grep -c . "$fx/observed.txt"
