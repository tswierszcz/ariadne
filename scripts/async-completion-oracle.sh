#!/usr/bin/env bash
# ASYNC_CALLBACKS a3-7 oracle: builds testdata/async-completion/app.jar and
# runs cf.Main (CompletableFutures completed by hand, normally and exceptionally) under
# scripts/MethodBreakTrace.java, writing every cf.* method body that ran to
# observed.txt. No network.
#
# Usage: scripts/async-completion-oracle.sh
set -euo pipefail
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
fx="$root/testdata/async-completion"
java "$root/scripts/JavaBuild.java" "$fx/src" "$fx/app.jar" 11
java "$root/scripts/MethodBreakTrace.java" "$fx/app.jar" cf.Main "$fx/observed.raw" 'cf.*'
{
    echo "# generated by scripts/async-completion-oracle.sh on $(java -version 2>&1 | head -1)"
    echo "# cf.* method bodies that ran on the real JVM (owner#name+desc)"
    LC_ALL=C sort -u "$fx/observed.raw" | grep -v '\$\$Lambda'
} > "$fx/observed.txt"
rm "$fx/observed.raw"
cat "$fx/observed.txt"
