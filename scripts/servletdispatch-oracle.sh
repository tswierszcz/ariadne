#!/usr/bin/env bash
# Servlet container dispatch oracle (FRAMEWORKS F2 / JVM_GRAPH, model
# servlet-container:dispatch). Compiles testdata/servletdispatch/src
# against the real javax.servlet API (jakarta.servlet-api 4.0.4, the
# javax.servlet package; by default the copy prepared by
# scripts/prepare-webgoat.sh) — a minimal container that reads
# WEB-INF/web.xml, creates the declared servlets and filters by class name
# and dispatches requests through Filter#doFilter and Servlet#service, as
# Tomcat's ApplicationFilterChain does; two registered servlets (one
# reached through HttpServlet's template dispatch), one registered filter,
# and a servlet and a filter that are on the class path but never
# registered. Packs testdata/servletdispatch/sd.war (WEB-INF/classes,
# WEB-INF/lib/servlet-api-classes.jar — the API jar's classes without
# its Maven metadata —, WEB-INF/web.xml), runs sd.Oracle on the real
# JVM, which prints every traced method body that ran, and writes
# testdata/servletdispatch/observed.txt. The war and the file are
# committed; cmd/ariadne TestGraphBenchmarkFixtures checks the graph
# against them without a JDK. A body not observed is not proven never to
# run: only this run was observed.
#
# Usage: scripts/servletdispatch-oracle.sh [JAVA_HOME] [SERVLET_API_JAR]
set -euo pipefail
JAVA_HOME_ARG="${1:-${JAVA_HOME:-}}"
if [ -n "$JAVA_HOME_ARG" ]; then
    export JAVA_HOME="$JAVA_HOME_ARG"
    export PATH="$JAVA_HOME/bin:$PATH"
fi
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
api="${2:-$root/work/WebGoat/app-dependency/jakarta.servlet-api-4.0.4.jar}"
fx="$root/testdata/servletdispatch"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
java "$root/scripts/JavaBuild.java" "$fx/src" "$tmp/classes.jar" 17 "$api"
mkdir -p "$tmp/war/WEB-INF/classes" "$tmp/war/WEB-INF/lib"
(cd "$tmp/war/WEB-INF/classes" && unzip -q "$tmp/classes.jar" -x 'META-INF/*')
# the API's classes byte for byte, without META-INF/maven: an unidentified
# jar has no Maven coordinate, so the offline test needs no OSV data for it
mkdir -p "$tmp/api"
(cd "$tmp/api" && unzip -q "$api" -x 'META-INF/maven/*')
cp "$fx/web/WEB-INF/web.xml" "$tmp/war/WEB-INF/web.xml"
cat > "$tmp/Pack.java" <<'J'
import java.util.spi.ToolProvider;
public class Pack {
    public static void main(String[] a) {
        System.exit(ToolProvider.findFirst("jar").orElseThrow().run(System.out, System.err,
            "--create", "--no-manifest", "--file", a[0], "--date", "2026-01-01T00:00:00Z", "-C", a[1], "."));
    }
}
J
java "$tmp/Pack.java" "$tmp/war/WEB-INF/lib/servlet-api-classes.jar" "$tmp/api"
rm -f "$fx/sd.war"
java "$tmp/Pack.java" "$fx/sd.war" "$tmp/war"
{
    echo "# generated by scripts/servletdispatch-oracle.sh on $(java -version 2>&1 | head -1), $(basename "$api")"
    java -cp "$tmp/classes.jar:$api" sd.Oracle "$fx/web/WEB-INF/web.xml"
} > "$fx/observed.txt"
cat "$fx/observed.txt"
