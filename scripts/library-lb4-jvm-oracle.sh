#!/usr/bin/env bash
# LIBRARY_MODE LB4 JVM oracles for the qualification set's facade,
# factory/subclass and SPI libraries (testdata/library-lb4/EXPECTED.MD):
# commons-configuration2 2.7, jackson-dataformat-yaml 2.12.3, jjwt-jackson
# 0.11.2. For each, builds testdata/library-lb4/<lib>/client.jar (a client
# that uses only the library's public API, sources in client/fx) and runs
# it under scripts/MethodBreakTrace.java (JDI, one-shot breakpoints) on
# every class of the library and every class of a mapped method
# (mapped.txt: all findings, REACHABLE or not) and any class listed in
# trace-classes.txt (inherited API), writing observed.txt: the
# library's and the mapped classes' method bodies that ran (lambda hidden
# classes left out). Jars: work/libs/<lib> (scripts/library-measure.sh);
# no network.
#
# Usage: scripts/library-lb4-jvm-oracle.sh [lib...]
set -euo pipefail
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
declare -A main=([configuration2]=fx.ConfigClient [jackson-yaml]=fx.YamlClient [jjwt-jackson]=fx.JwtJsonClient)
libs=("$@")
[ ${#libs[@]} -eq 0 ] && libs=(configuration2 jackson-yaml jjwt-jackson)
for lib in "${libs[@]}"; do
    fx="$root/testdata/library-lb4/$lib"
    d="$root/work/libs/$lib"
    cp="$d/lib.jar"
    for j in "$d"/deps/*.jar; do cp="$cp:$j"; done
    java "$root/scripts/JavaBuild.java" "$fx/client" "$fx/client.jar" 11 "$cp"
    mapfile -t classes < <({
        unzip -Z1 "$d/lib.jar" | grep '\.class$' | grep -v '^META-INF/' | sed 's/\.class$//; s#/#.#g'
        grep -v '^#' "$fx/mapped.txt" | cut -f3 | sed 's/#.*//'
        if [ -f "$fx/trace-classes.txt" ]; then grep -v '^#' "$fx/trace-classes.txt"; fi
    } | sort -u)
    java "$root/scripts/MethodBreakTrace.java" "$fx/client.jar:$cp" "${main[$lib]}" "$fx/observed.raw" "${classes[@]}" > "$fx/run.log" 2>&1
    {
        echo "# generated by scripts/library-lb4-jvm-oracle.sh on $(java -version 2>&1 | head -1)"
        echo "# method bodies of $lib's classes and of mapped classes that ran (owner#name+desc)"
        grep -v '\$\$Lambda' "$fx/observed.raw" | sort -u
    } > "$fx/observed.txt"
    rm "$fx/observed.raw"
    echo "== $lib: $(grep -vc '^#' "$fx/observed.txt") methods ran"
    grep -E '^[a-z-]+: ' "$fx/run.log" || true
done
