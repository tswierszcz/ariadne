#!/usr/bin/env bash
# CompletionStage continuations oracle (ASYNC_CALLBACKS A3, slice 1).
# Compiles testdata/continuations/src into testdata/continuations/app.jar
# and runs fx.c.Main on the real JVM; every callback body records itself
# (fx.trace.Ran, from any thread). Cases: two continuations after
# supplyAsync, thenCompose, thenCombine, a failing stage (thenApply skipped,
# exceptionally/handle/whenComplete run), a succeeding stage (exceptionally
# never runs), runAsync/thenRunAsync on an executor, a call through the
# CompletionStage interface, a future nothing completes, and a callback
# passed through a parameter. Writes testdata/continuations/observed.txt.
# The jar and the file are committed; TestContinuationsOracle needs no JDK.
#
# Usage: scripts/continuations-oracle.sh [JAVA_HOME]
set -euo pipefail
JAVA_HOME_ARG="${1:-${JAVA_HOME:-}}"
if [ -n "$JAVA_HOME_ARG" ]; then
    export JAVA_HOME="$JAVA_HOME_ARG"
    export PATH="$JAVA_HOME/bin:$PATH"
fi
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
fx="$root/testdata/continuations"
java "$root/scripts/JavaBuild.java" "$fx/src" "$fx/app.jar" 17
{
    echo "# generated by scripts/continuations-oracle.sh on $(java -version 2>&1 | head -1)"
    java -cp "$fx/app.jar" fx.c.Main
} > "$fx/observed.txt"
cat "$fx/observed.txt"
