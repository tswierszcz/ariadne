#!/usr/bin/env bash
# GRAPH_PRECISION P3 oracle (p3-1): receiver allocation narrowing.
# Builds testdata/pta/app.jar from app/ (no dependencies) and runs
# fx.app.Main on the real JVM; each Shape#area body records the call that entered it.
# Writes testdata/pta/observed.txt. The jar and the file are
# committed; TestPTAOracle needs no JDK.
#
# Usage: scripts/pta-oracle.sh [JAVA_HOME]
set -euo pipefail
JAVA_HOME_ARG="${1:-${JAVA_HOME:-}}"
if [ -n "$JAVA_HOME_ARG" ]; then
    export JAVA_HOME="$JAVA_HOME_ARG"
    export PATH="$JAVA_HOME/bin:$PATH"
fi
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
fx="$root/testdata/pta"
java "$root/scripts/JavaBuild.java" "$fx/app" "$fx/app.jar" 11
{
    echo "# generated by scripts/pta-oracle.sh on $(java -version 2>&1 | head -1)"
    java -cp "$fx/app.jar" fx.app.Main
} > "$fx/observed.txt"
grep -c . "$fx/observed.txt"
