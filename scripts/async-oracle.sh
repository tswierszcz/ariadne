#!/usr/bin/env bash
# ASYNC_CALLBACKS A0–A2 and MethodHandle (DYNAMIC_LINKAGE L2) oracle
# (ROADMAP B4). Compiles testdata/async/src into testdata/async/app.jar and
# runs fx.a.Main on the real JVM; every case records the bodies that ran
# (fx.trace.Ran, from any thread). Writes testdata/async/observed.txt. The
# jar and the file are committed, and cmd/ariadne TestAsyncOracle checks
# the call graph against them without a JDK.
#
# Usage: scripts/async-oracle.sh [JAVA_HOME]
set -euo pipefail
JAVA_HOME_ARG="${1:-${JAVA_HOME:-}}"
if [ -n "$JAVA_HOME_ARG" ]; then
    export JAVA_HOME="$JAVA_HOME_ARG"
    export PATH="$JAVA_HOME/bin:$PATH"
fi
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
fx="$root/testdata/async"
java "$root/scripts/JavaBuild.java" "$fx/src" "$fx/app.jar" 17
{
    echo "# generated by scripts/async-oracle.sh on $(java -version 2>&1 | head -1)"
    java -cp "$fx/app.jar" fx.a.Main
} > "$fx/observed.txt"
cat "$fx/observed.txt"
