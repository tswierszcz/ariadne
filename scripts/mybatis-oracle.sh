#!/usr/bin/env bash
# MyBatis mapper proxy (framework:proxies) oracle (ROADMAP B4). Builds
# testdata/mybatis:
#   deps/mybatis-3.4.1.jar  the real MyBatis (Apache 2.0), copied in without
#                           META-INF/maven (no GAV is identified, so the
#                           offline test makes no OSV query); every class
#                           is byte-identical to the original, whose
#                           SHA-256 is written to deps/mybatis-3.4.1.sha256
#   deps/stub.jar           abstract stubs of the JDBC interfaces
#                           (scripts/JdbcStubs.java) and fx.trace.Ran
#   deps/driver.jar         a driver registered in META-INF/services; its
#                           bodies record every frame on the stack
#   app.jar                 fx.app.Main: an @Mapper interface queried
#                           through an UnpooledDataSource (DriverManager)
# and runs Main on the real JVM. Writes testdata/mybatis/observed.txt: the
# bodies the JVM ran on the way to the driver (application, MyBatis,
# driver, JDK, generated proxy frames — TestMyBatisOracle keeps those of
# the input). The jars and the file are committed; the test needs no JDK.
#
# Usage: scripts/mybatis-oracle.sh [JAVA_HOME] (mybatis-3.4.1.jar is read
# from ~/.m2 when deps/ does not have it)
set -euo pipefail
JAVA_HOME_ARG="${1:-${JAVA_HOME:-}}"
if [ -n "$JAVA_HOME_ARG" ]; then
    export JAVA_HOME="$JAVA_HOME_ARG"
    export PATH="$JAVA_HOME/bin:$PATH"
fi
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
fx="$root/testdata/mybatis"
mb="$fx/deps/mybatis-3.4.1.jar"
if [ ! -f "$mb" ]; then
    orig="$HOME/.m2/repository/org/mybatis/mybatis/3.4.1/mybatis-3.4.1.jar"
    sha256sum "$orig" | cut -d' ' -f1 > "$fx/deps/mybatis-3.4.1.sha256"
    python3 -I - "$orig" "$mb" <<'PY'
import sys, zipfile
src, dst = sys.argv[1], sys.argv[2]
with zipfile.ZipFile(src) as zi, zipfile.ZipFile(dst, "w", zipfile.ZIP_DEFLATED) as zo:
    for info in zi.infolist():
        if not info.filename.startswith("META-INF/maven/"):
            zo.writestr(info, zi.read(info))
PY
fi
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
mkdir -p "$tmp/stub/fx/stub"
cp -r "$fx/trace/." "$tmp/stub/"
java "$root/scripts/JdbcStubs.java" "$tmp/stub/fx/stub" fx.stub java.sql.Connection java.sql.PreparedStatement \
    java.sql.ResultSet java.sql.ResultSetMetaData java.sql.DatabaseMetaData
java "$root/scripts/JavaBuild.java" "$tmp/stub" "$fx/deps/stub.jar" 17
java "$root/scripts/JavaBuild.java" "$fx/driver" "$fx/deps/driver.jar" 17 "$fx/deps/stub.jar"
java "$root/scripts/JavaBuild.java" "$fx/app" "$fx/app.jar" 17 "$fx/deps/stub.jar:$mb"
cat > "$tmp/AddResources.java" <<'J'
import java.util.spi.ToolProvider;
public class AddResources {
    public static void main(String[] a) {
        System.exit(ToolProvider.findFirst("jar").orElseThrow().run(System.out, System.err,
            "--update", "--file", a[0], "--date", "2026-01-01T00:00:00Z", "-C", a[1], "."));
    }
}
J
java "$tmp/AddResources.java" "$fx/deps/driver.jar" "$fx/driver-resources"
{
    echo "# generated by scripts/mybatis-oracle.sh on $(java -version 2>&1 | head -1)"
    java -cp "$fx/app.jar:$fx/deps/stub.jar:$fx/deps/driver.jar:$mb" fx.app.Main
} > "$fx/observed.txt"
grep -c . "$fx/observed.txt"
