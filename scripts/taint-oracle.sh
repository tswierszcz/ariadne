#!/usr/bin/env bash
# DATA_FLOW D5 real-JVM oracle for the taint pilot. Rebuilds
# testdata/taint/app.jar (scripts/build-taint-fixture.sh, Java 17 — the
# oracle uses ObjectInputFilter.Config.setSerialFilterFactory), compiles
# testdata/taint/oracle/src into oracle.jar, and runs oracle.TaintOracle:
# every stub-@PostMapping handler is called with a serialized Canary as
# request data, and a process-wide filter factory records each entry
# (the method calling ObjectInputStream's read) that read a Canary —
# "read", or "rejected" when the entry's own filter refused it.
# Writes testdata/taint/oracle/observed.tsv; the jars and the TSV are
# committed, and internal/taint TestTaintOracle compares the model with
# them without a JDK. An entry not observed here is not proven
# unreachable by request data: the oracle covers these calls only.
#
# Usage: scripts/taint-oracle.sh [JAVA_HOME]
set -euo pipefail
JAVA_HOME_ARG="${1:-${JAVA_HOME:-}}"
if [ -n "$JAVA_HOME_ARG" ]; then
    export JAVA_HOME="$JAVA_HOME_ARG"
    export PATH="$JAVA_HOME/bin:$PATH"
fi
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
o="$root/testdata/taint/oracle"
"$root/scripts/build-taint-fixture.sh"
java "$root/scripts/JavaBuild.java" "$o/src" "$o/oracle.jar" 17 "$root/testdata/taint/app.jar"
{
    echo "# entry	what the real JVM did with the Canary sent as request data (read / rejected by the entry's filter)"
    echo "# generated by scripts/taint-oracle.sh on $(java -version 2>&1 | head -1)"
    java -cp "$root/testdata/taint/app.jar:$o/oracle.jar" oracle.TaintOracle | grep -v "^  "
} > "$o/observed.tsv"
cat "$o/observed.tsv"
