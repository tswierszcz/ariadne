#!/usr/bin/env bash
# Library Micronaut bean-definition oracle (LIBRARY_MODE LB2, Micronaut
# measurement). Builds testdata/library-micronaut/lib.jar (the control
# library: cases (t)-(x), see its EXPECTED.MD) with Micronaut 3.9.7's
# annotation processor, which generates the $X$Definition classes and
# their META-INF/micronaut/io.micronaut.inject.BeanDefinitionReference
# entries, against commons-text 1.9; builds client.jar (fx.Main: boots
# Micronaut and uses each bean once), runs it under scripts/MethodTrace.java
# (JDI) and writes every mn.* body and StringSubstitutor#replace the JVM
# entered to observed.txt. Micronaut is read from work/micronaut-oracle/lib,
# fetched once with (pom.xml: micronaut-inject-java and micronaut-context
# 3.9.7):
#   (cd work/micronaut-oracle && mvn dependency:copy-dependencies -DoutputDirectory=lib)
# and never committed. The jars and observed.txt are committed; the Go
# tests need no JDK.
#
# Usage: scripts/library-micronaut-oracle.sh
set -euo pipefail
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
fx="$root/testdata/library-micronaut"
deps="$root/testdata/library/deps"
mn="$(ls "$root"/work/micronaut-oracle/lib/*.jar | grep -v snakeyaml | tr '\n' : | sed 's/:$//')"
text="$deps/commons-text-1.9.jar:$deps/commons-lang3-3.11.jar"
java "$root/scripts/JavaBuild.java" "$fx/lib" "$fx/lib.jar" 11 "$text:$mn" proc
java "$root/scripts/JavaBuild.java" "$fx/client" "$fx/client.jar" 11 "$fx/lib.jar:$mn"
java "$root/scripts/MethodTrace.java" "$fx/client.jar:$fx/lib.jar:$text:$mn" fx.Main "$fx/observed.raw" 'mn.*' 'org.apache.commons.text.StringSubstitutor'
{
    echo "# generated by scripts/library-micronaut-oracle.sh on $(java -version 2>&1 | head -1) with Micronaut 3.9.7"
    echo "# mn.* (without generated \$...\$Definition classes) and StringSubstitutor method bodies that ran on the real JVM (owner#name+desc)"
    grep -E '^mn\.|#replace\(' "$fx/observed.raw" | grep -v '^mn\.internal\.\$' | sort -u
} > "$fx/observed.txt"
rm "$fx/observed.raw"
cat "$fx/observed.txt"
