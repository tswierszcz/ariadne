#!/usr/bin/env bash
# ASYNC_CALLBACKS a3-4 oracle: builds testdata/async-returned/app.jar and
# runs ar.Main (the strategy loop on a second thread, a real executor) under
# scripts/MethodBreakTrace.java, writing every ar.* method body that ran to
# observed.txt. No network.
#
# Usage: scripts/async-returned-oracle.sh
set -euo pipefail
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
fx="$root/testdata/async-returned"
java "$root/scripts/JavaBuild.java" "$fx/src" "$fx/app.jar" 11
java "$root/scripts/MethodBreakTrace.java" "$fx/app.jar" ar.Main "$fx/observed.raw" 'ar.*'
{
    echo "# generated by scripts/async-returned-oracle.sh on $(java -version 2>&1 | head -1)"
    echo "# ar.* method bodies that ran on the real JVM (owner#name+desc)"
    LC_ALL=C sort -u "$fx/observed.raw" | grep -v '\$\$Lambda'
} > "$fx/observed.txt"
rm "$fx/observed.raw"
cat "$fx/observed.txt"
