#!/usr/bin/env bash
# Programmatic servlet/filter registration oracle (servlet-container:dispatch
# s3). Compiles testdata/servletprog/src against the real javax.servlet API
# (jakarta.servlet-api 4.0.4, the javax.servlet package; by default the copy
# prepared by scripts/prepare-webgoat.sh) — a minimal container with no
# web.xml that loads its ServletContainerInitializer through ServiceLoader,
# hands it the scanned classes matching @HandlesTypes (Spring's
# SpringServletContainerInitializer shape: the initializer creates them
# reflectively and runs their onStartup) and records what they register on
# the ServletContext: a servlet a factory method returns under an abstract
# declared type (AbstractDispatcherServletInitializer's shape), a `new`
# servlet, a filter class literal passed through a helper's parameter, and
# a filter class name. An abstract initializer no class extends and a
# class that is not an initializer register servlets/filters too; nothing
# runs them. Packs testdata/servletprog/sp.war (WEB-INF/classes with
# META-INF/services, WEB-INF/lib/servlet-api-classes.jar), runs sp.Oracle on
# the real JVM, which prints every traced method body that ran, and writes
# testdata/servletprog/observed.txt. The war and the file are committed;
# cmd/ariadne TestGraphBenchmarkFixtures checks the graph against them.
#
# Usage: scripts/servletprog-oracle.sh [JAVA_HOME] [SERVLET_API_JAR]
set -euo pipefail
JAVA_HOME_ARG="${1:-${JAVA_HOME:-}}"
if [ -n "$JAVA_HOME_ARG" ]; then
    export JAVA_HOME="$JAVA_HOME_ARG"
    export PATH="$JAVA_HOME/bin:$PATH"
fi
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
api="${2:-$root/work/WebGoat/app-dependency/jakarta.servlet-api-4.0.4.jar}"
fx="$root/testdata/servletprog"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
java "$root/scripts/JavaBuild.java" "$fx/src" "$tmp/classes.jar" 17 "$api"
mkdir -p "$tmp/war/WEB-INF/classes" "$tmp/war/WEB-INF/lib" "$tmp/api"
(cd "$tmp/war/WEB-INF/classes" && unzip -q "$tmp/classes.jar" -x 'META-INF/MANIFEST.MF')
(cd "$tmp/api" && unzip -q "$api" -x 'META-INF/maven/*')
cat > "$tmp/Pack.java" <<'J'
import java.util.spi.ToolProvider;
public class Pack {
    public static void main(String[] a) {
        System.exit(ToolProvider.findFirst("jar").orElseThrow().run(System.out, System.err,
            "--create", "--no-manifest", "--file", a[0], "--date", "2026-01-01T00:00:00Z", "-C", a[1], "."));
    }
}
J
java "$tmp/Pack.java" "$tmp/war/WEB-INF/lib/servlet-api-classes.jar" "$tmp/api"
rm -f "$fx/sp.war"
java "$tmp/Pack.java" "$fx/sp.war" "$tmp/war"
{
    echo "# generated by scripts/servletprog-oracle.sh on $(java -version 2>&1 | head -1), $(basename "$api")"
    java -cp "$tmp/classes.jar:$api" sp.Oracle
} > "$fx/observed.txt"
cat "$fx/observed.txt"
