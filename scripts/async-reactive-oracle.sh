#!/usr/bin/env bash
# ASYNC_CALLBACKS a3-6 oracle: builds testdata/async-reactive/app.jar and
# runs rx.Main (real SubmissionPublishers delivering on the common pool) under
# scripts/MethodBreakTrace.java, writing every rx.* method body that ran to
# observed.txt. No network.
#
# Usage: scripts/async-reactive-oracle.sh
set -euo pipefail
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
fx="$root/testdata/async-reactive"
java "$root/scripts/JavaBuild.java" "$fx/src" "$fx/app.jar" 11
java "$root/scripts/MethodBreakTrace.java" "$fx/app.jar" rx.Main "$fx/observed.raw" 'rx.*'
{
    echo "# generated by scripts/async-reactive-oracle.sh on $(java -version 2>&1 | head -1)"
    echo "# rx.* method bodies that ran on the real JVM (owner#name+desc)"
    LC_ALL=C sort -u "$fx/observed.raw" | grep -v '\$\$Lambda'
} > "$fx/observed.txt"
rm "$fx/observed.raw"
cat "$fx/observed.txt"
