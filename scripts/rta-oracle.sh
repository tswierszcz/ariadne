#!/usr/bin/env bash
# GRAPH_PRECISION P2 RTA oracle. Compiles testdata/rta/src (a Shape
# interface with three implementations called through it — one created
# only in a factory method —, one created only where nothing calls, one
# never created; a dispatch cycle whose allocations are discovered late;
# a ServiceLoader provider; two classes created by a reflective factory
# whose class name is built at run time, one annotated, one named
# nowhere) into testdata/rta/rta.jar with the real javac, adds
# META-INF/services, and runs rt.Oracle on the real JVM, which prints
# every method body that ran. Writes testdata/rta/observed.txt; the jar and
# the file are committed, and cmd/ariadne TestRTAOracle checks the RTA
# graph against them without a JDK. A body not observed is not proven
# never to run: only this run was observed.
#
# Usage: scripts/rta-oracle.sh [JAVA_HOME]
set -euo pipefail
JAVA_HOME_ARG="${1:-${JAVA_HOME:-}}"
if [ -n "$JAVA_HOME_ARG" ]; then
    export JAVA_HOME="$JAVA_HOME_ARG"
    export PATH="$JAVA_HOME/bin:$PATH"
fi
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
fx="$root/testdata/rta"
java "$root/scripts/JavaBuild.java" "$fx/src" "$fx/rta.jar" 17
# add the provider registration (JavaBuild jars compiled classes only)
cat > "$fx/.AddResources.java" <<'J'
import java.util.spi.ToolProvider;
public class AddResources {
    public static void main(String[] a) {
        System.exit(ToolProvider.findFirst("jar").orElseThrow().run(System.out, System.err,
            "--update", "--file", a[0], "--date", "2026-01-01T00:00:00Z", "-C", a[1], "."));
    }
}
J
java "$fx/.AddResources.java" "$fx/rta.jar" "$fx/resources"
rm -f "$fx/.AddResources.java"
{
    echo "# generated by scripts/rta-oracle.sh on $(java -version 2>&1 | head -1)"
    java -cp "$fx/rta.jar" rt.Oracle
} > "$fx/observed.txt"
cat "$fx/observed.txt"
