#!/usr/bin/env bash
# Spring AOP oracle (spring:aop).
# Builds testdata/aop/app.jar against the Spring Framework 5.3.6 jars
# testdata/tx already holds (scripts/tx-oracle.sh; no copy here) and
# aspectjweaver 1.9.6 (Spring parses pointcuts with it; only the run needs
# it, the analysis reads the annotations by name):
#   fx.app.Main calls advised beans: OrderService (CGLIB: a self-invocation,
#   a final method, an @Audited method), JdbcRepo behind a JDK proxy (save
#   returns, find throws) and the @Monitored ReportService. TracingAspect
#   has @Before on a named pointcut, @AfterReturning, @AfterThrowing,
#   @Around with a bound annotation, @Before on @within, one advice that
#   matches nothing and one with args(...). Unregistered is an @Aspect that
#   is no bean.
# and runs Main on the real JVM. Writes testdata/aop/observed.txt.
# The jar and the file are committed; TestAOPOracle needs no JDK.
#
# Usage: scripts/aop-oracle.sh [ASPECTJWEAVER_JAR] [JAVA_HOME]
set -euo pipefail
weaver="${1:-$HOME/.m2/repository/org/aspectj/aspectjweaver/1.9.6/aspectjweaver-1.9.6.jar}"
JAVA_HOME_ARG="${2:-${JAVA_HOME:-}}"
if [ -n "$JAVA_HOME_ARG" ]; then
    export JAVA_HOME="$JAVA_HOME_ARG"
    export PATH="$JAVA_HOME/bin:$PATH"
fi
# aspectjweaver-1.9.6.jar from Maven Central.
echo "3167577eaa4be02817295d320c5a6578de8b80d15615d719d5be0a0d65d16165  $weaver" | sha256sum -c --quiet -
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
fx="$root/testdata/aop"
deps="$root/testdata/tx/deps"
cp_list=""
for j in spring-jcl spring-core spring-beans spring-aop spring-context spring-expression; do
    cp_list="$cp_list:$deps/$j-5.3.6.jar"
done
cp_list="${cp_list#:}:$weaver"
java "$root/scripts/JavaBuild.java" "$fx/app" "$fx/app.jar" 11 "$cp_list"
{
    echo "# generated by scripts/aop-oracle.sh on $(java -version 2>&1 | head -1)"
    java -cp "$fx/app.jar:$cp_list" fx.app.Main
} > "$fx/observed.txt"
grep -c . "$fx/observed.txt"
