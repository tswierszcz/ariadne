#!/usr/bin/env bash
# Library CDI bean-archive oracle (LIBRARY_MODE LB2, CDI announcements).
# Builds testdata/library-cdi/lib.jar (the control library: cases (t)-(x),
# see its EXPECTED.MD; a bean archive with META-INF/beans.xml) against
# commons-text 1.9 and the CDI API, and client.jar (fx.Main: boots Weld SE
# and uses the library's beans), then runs the client under
# scripts/MethodTrace.java (JDI) and writes every cd.* body and
# StringSubstitutor#replace the JVM entered to observed.txt. Weld SE
# (weld-se-shaded 5.1.2.Final, CDI 4.0, which carries the Jakarta APIs) is
# read from work/cdi-oracle/lib, fetched once with:
#   (cd work/cdi-oracle && mvn dependency:copy-dependencies -DoutputDirectory=lib)
# and never committed; the analysis dependencies are testdata/library/deps.
# The jars and the file are committed; the Go tests need no JDK.
#
# Usage: scripts/library-cdi-oracle.sh
set -euo pipefail
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
fx="$root/testdata/library-cdi"
deps="$root/testdata/library/deps"
weld="$root/work/cdi-oracle/lib/weld-se-shaded-5.1.2.Final.jar"
text="$deps/commons-text-1.9.jar:$deps/commons-lang3-3.11.jar"
java "$root/scripts/JavaBuild.java" "$fx/lib" "$fx/lib.jar" 11 "$text:$weld"
java "$root/scripts/JavaBuild.java" "$fx/client" "$fx/client.jar" 11 "$fx/lib.jar:$weld"
java "$root/scripts/MethodTrace.java" "$fx/client.jar:$fx/lib.jar:$text:$weld" fx.Main "$fx/observed.raw" 'cd.*' 'org.apache.commons.text.StringSubstitutor'
{
    echo "# generated by scripts/library-cdi-oracle.sh on $(java -version 2>&1 | head -1) with Weld SE 5.1.2.Final"
    echo "# cd.* and StringSubstitutor method bodies that ran on the real JVM (owner#name+desc)"
    grep -v '\$\$Lambda/\|\$Proxy\$\|WeldClientProxy\|WeldSubclass' "$fx/observed.raw" | grep -E '^cd\.|#replace\(' | sort -u
} > "$fx/observed.txt"
rm "$fx/observed.raw"
cat "$fx/observed.txt"
