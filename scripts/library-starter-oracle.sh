#!/usr/bin/env bash
# LIBRARY_MODE starter oracle (after LB4): which of the mapped vulnerable
# methods behind the 26 REACHABLE findings of
# mybatis-spring-boot-autoconfigure 2.1.2 (-roots api) run in the smallest
# real application of the starter (testdata/library-starter/app: Spring
# Boot 2.2.5, embedded HSQLDB, one @Mapper), without and with an
# application.yml. Builds app.jar, runs fx.App twice under
# scripts/MethodBreakTrace.java (JDI, one-shot breakpoints) on each mapped class
# (mapped.txt) and writes observed-plain.txt / observed-yml.txt.
# Jars: work/libs/mybatis-starter/all (scripts/library-measure.sh) and
# hsqldb 2.5.1 from the local Maven repository; no network.
#
# Usage: scripts/library-starter-oracle.sh
set -euo pipefail
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
fx="$root/testdata/library-starter"
cp="$(ls "$root"/work/libs/mybatis-starter/all/*.jar | tr '\n' ':')$HOME/.m2/repository/org/hsqldb/hsqldb/2.5.1/hsqldb-2.5.1.jar"
java "$root/scripts/JavaBuild.java" "$fx/app" "$fx/app.jar" 11 "$cp"
mapfile -t classes < <(grep -v '^#' "$fx/mapped.txt" | cut -f2 | sed 's/#.*//' | sort -u)
for scenario in plain yml; do
    extra=""
    [ "$scenario" = yml ] && extra="$fx/yml:"
    java "$root/scripts/MethodBreakTrace.java" "$extra$fx/app.jar:$cp" fx.App "$fx/observed.raw" "${classes[@]}"
    {
        echo "# generated by scripts/library-starter-oracle.sh ($scenario) on $(java -version 2>&1 | head -1)"
        echo "# bodies of mapped classes (mapped.txt) that ran on the real JVM (owner#name+desc)"
        sort -u "$fx/observed.raw"
    } > "$fx/observed-$scenario.txt"
    rm "$fx/observed.raw"
done
