#!/usr/bin/env bash
# ASYNC_CALLBACKS a4-1 oracle: builds testdata/async-threads/app.jar and
# runs th.Main (started Thread subclasses, a saturated pool rejecting a task) under
# scripts/MethodBreakTrace.java, writing every th.* method body that ran to
# observed.txt. No network.
#
# Usage: scripts/async-threads-oracle.sh
set -euo pipefail
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
fx="$root/testdata/async-threads"
java "$root/scripts/JavaBuild.java" "$fx/src" "$fx/app.jar" 11
java "$root/scripts/MethodBreakTrace.java" "$fx/app.jar" th.Main "$fx/observed.raw" 'th.*'
{
    echo "# generated by scripts/async-threads-oracle.sh on $(java -version 2>&1 | head -1)"
    echo "# th.* method bodies that ran on the real JVM (owner#name+desc)"
    LC_ALL=C sort -u "$fx/observed.raw" | grep -v '\$\$Lambda'
} > "$fx/observed.txt"
rm "$fx/observed.raw"
cat "$fx/observed.txt"
