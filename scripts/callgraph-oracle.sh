#!/usr/bin/env bash
# GRAPH_PRECISION P0 known-target oracle. Compiles testdata/callgraph/src
# (interface implementations at several depths, overloads, a default
# method, a generic bridge, a covariant-return bridge, an inherited body,
# a super call) into testdata/callgraph/cg.jar with the real javac, and
# runs cg.Oracle on the real JVM: every call site of cg.Sites is driven
# with every receiver the fixture can create, and each method body
# records that it ran for that site. Writes testdata/callgraph/observed.tsv
# (site, method that ran). The jar and the TSV are committed;
# internal/callgraph TestKnownTargets checks the graph against them
# without a JDK. A method not observed for a site is not proven never
# to run there: only these receivers were tried.
#
# Usage: scripts/callgraph-oracle.sh [JAVA_HOME]
set -euo pipefail
JAVA_HOME_ARG="${1:-${JAVA_HOME:-}}"
if [ -n "$JAVA_HOME_ARG" ]; then
    export JAVA_HOME="$JAVA_HOME_ARG"
    export PATH="$JAVA_HOME/bin:$PATH"
fi
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
fx="$root/testdata/callgraph"
java "$root/scripts/JavaBuild.java" "$fx/src" "$fx/cg.jar" 17
{
    echo "# site	method body that ran on the real JVM (owner#name+desc)"
    echo "# generated by scripts/callgraph-oracle.sh on $(java -version 2>&1 | head -1)"
    java -cp "$fx/cg.jar" cg.Oracle
} > "$fx/observed.tsv"
cat "$fx/observed.tsv"
