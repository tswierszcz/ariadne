#!/usr/bin/env bash
# DESERIALIZATION Z4 real-JVM oracle. Compiles testdata/deserialize/oracle
# into three jars and records what the real JVM runs when each scenario
# object is read through each entry:
#   scenarios.jar  sc.* — the entries (sc.Entries#plain, #filtered with
#                  createFilter("sc.PrivateCb;!*")) and the scenario classes:
#                  private callbacks, a public readObject, Externalizable, a
#                  record, a class serializable only through an unlisted JDK base
#   lib.jar        lib.Cb — a library class with a private readObject
#   shaded.jar     shaded.lib.Cb — the same class relocated (a second instance)
# Writes observed.tsv: entry, object class, callbacks that ran (or "-"),
# and REJECTED when the filter refused it. The jars and observed.tsv are
# committed; internal/deserialize TestDeserializationOracle compares
# ariadne's model with them without a JDK.
#
# Usage: scripts/deserialize-oracle.sh [JAVA_HOME]
set -euo pipefail
JAVA_HOME_ARG="${1:-${JAVA_HOME:-}}"
if [ -n "$JAVA_HOME_ARG" ]; then
    export JAVA_HOME="$JAVA_HOME_ARG"
    export PATH="$JAVA_HOME/bin:$PATH"
fi
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
o="$root/testdata/deserialize/oracle"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
mkdir -p "$tmp/lib/lib" "$tmp/shaded/shaded/lib"
cp "$o/shaded-src/lib/Cb.java" "$tmp/lib/lib/"
cp "$o/shaded-src/shaded/lib/Cb.java" "$tmp/shaded/shaded/lib/"
java "$root/scripts/JavaBuild.java" "$o/src" "$o/scenarios.jar" 17
java "$root/scripts/JavaBuild.java" "$tmp/lib" "$o/lib.jar" 17 "$o/scenarios.jar"
java "$root/scripts/JavaBuild.java" "$tmp/shaded" "$o/shaded.jar" 17 "$o/scenarios.jar"
java -version 2>&1 | head -1
{
    echo "# entry	object	callbacks run on the real JVM (in order; - = none)	[REJECTED exception]"
    echo "# generated by scripts/deserialize-oracle.sh on $(java -version 2>&1 | head -1)"
    java -cp "$o/scenarios.jar:$o/lib.jar:$o/shaded.jar" sc.Oracle
} > "$o/observed.tsv"
cat "$o/observed.tsv"
