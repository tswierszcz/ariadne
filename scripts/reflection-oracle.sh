#!/usr/bin/env bash
# REFLECTION R0–R2 oracle (ROADMAP B4). Compiles testdata/reflection/src
# into testdata/reflection/app.jar and runs fx.r.Main on the real JVM; every
# case method records the bodies that ran (fx.trace.Ran). Writes
# testdata/reflection/observed.txt. The jar and the file are committed, and
# cmd/ariadne TestReflectionOracle checks the call graph against them
# without a JDK.
#
# Usage: scripts/reflection-oracle.sh [JAVA_HOME]
set -euo pipefail
JAVA_HOME_ARG="${1:-${JAVA_HOME:-}}"
if [ -n "$JAVA_HOME_ARG" ]; then
    export JAVA_HOME="$JAVA_HOME_ARG"
    export PATH="$JAVA_HOME/bin:$PATH"
fi
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
fx="$root/testdata/reflection"
java "$root/scripts/JavaBuild.java" "$fx/src" "$fx/app.jar" 17
{
    echo "# generated by scripts/reflection-oracle.sh on $(java -version 2>&1 | head -1)"
    java -cp "$fx/app.jar" fx.r.Main
} > "$fx/observed.txt"
cat "$fx/observed.txt"
