import java.lang.reflect.*;
import java.nio.file.*;
import java.util.*;

/**
 * Writes abstract stub classes implementing JDBC interfaces, every abstract
 * method throwing UnsupportedOperationException, so a fixture overrides only
 * the methods it needs (scripts/jdbc-oracle.sh).
 *
 * Usage: java scripts/JdbcStubs.java OUT_DIR PACKAGE IFACE...
 */
public class JdbcStubs {
    static String type(Class<?> c) { return c.getCanonicalName(); }

    public static void main(String[] a) throws Exception {
        Path dir = Path.of(a[0]);
        Files.createDirectories(dir);
        for (int i = 2; i < a.length; i++) {
            Class<?> iface = Class.forName(a[i]);
            String name = "Stub" + iface.getSimpleName();
            StringBuilder b = new StringBuilder("package " + a[1] + ";\n\n/** Generated by scripts/JdbcStubs.java. */\n")
                .append("@SuppressWarnings({\"rawtypes\", \"unchecked\"})\n")
                .append("public abstract class ").append(name).append(" implements ").append(iface.getName()).append(" {\n");
            Set<String> seen = new TreeSet<>();
            Method[] ms = iface.getMethods();
            Arrays.sort(ms, Comparator.comparing(Method::toString));
            for (Method m : ms) {
                if (m.isDefault() || Modifier.isStatic(m.getModifiers())) continue;
                StringJoiner ps = new StringJoiner(", ");
                StringBuilder key = new StringBuilder(m.getName());
                Class<?>[] p = m.getParameterTypes();
                for (int k = 0; k < p.length; k++) { ps.add(type(p[k]) + " a" + k); key.append(',').append(p[k].getName()); }
                if (!seen.add(key.toString())) continue;
                b.append("    public ").append(type(m.getReturnType())).append(' ').append(m.getName()).append('(').append(ps)
                 .append(") { throw new UnsupportedOperationException(\"").append(m.getName()).append("\"); }\n");
            }
            Files.writeString(dir.resolve(name + ".java"), b.append("}\n").toString());
        }
    }
}
