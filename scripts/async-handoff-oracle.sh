#!/usr/bin/env bash
# ASYNC_CALLBACKS a3-3 oracle: builds testdata/async-handoff/app.jar and
# runs ah.Main (the drains on a second thread, a real NIO Pipe and
# Selector) under scripts/MethodBreakTrace.java, writing every ah.* method
# body that ran to observed.txt. No network.
#
# Usage: scripts/async-handoff-oracle.sh
set -euo pipefail
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
fx="$root/testdata/async-handoff"
java "$root/scripts/JavaBuild.java" "$fx/src" "$fx/app.jar" 11
java "$root/scripts/MethodBreakTrace.java" "$fx/app.jar" ah.Main "$fx/observed.raw" 'ah.*'
{
    echo "# generated by scripts/async-handoff-oracle.sh on $(java -version 2>&1 | head -1)"
    echo "# ah.* method bodies that ran on the real JVM (owner#name+desc)"
    LC_ALL=C sort -u "$fx/observed.raw" | grep -v '\$\$Lambda'
} > "$fx/observed.txt"
rm "$fx/observed.raw"
cat "$fx/observed.txt"
