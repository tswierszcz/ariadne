#!/usr/bin/env bash
# Library mode oracle (LIBRARY_MODE LB0/LB1). Builds testdata/library/lib.jar
# (the control library: cases (a)-(f), see testdata/library/EXPECTED.MD)
# against commons-text 1.9, and client.jar (fx.Client: one call to every
# public entry, its own Listener for Pipeline#run), then runs the client
# under scripts/MethodTrace.java (JDI) and writes every lib.* body and
# StringSubstitutor#replace the JVM entered to testdata/library/observed.txt.
# The jars (commons-text 1.9 and commons-lang3 3.11 from Maven Central,
# checked below) and the file are committed; the Go tests need no JDK.
#
# Usage: scripts/library-oracle.sh [JAVA_HOME]
set -euo pipefail
JAVA_HOME_ARG="${1:-${JAVA_HOME:-}}"
if [ -n "$JAVA_HOME_ARG" ]; then
    export JAVA_HOME="$JAVA_HOME_ARG"
    export PATH="$JAVA_HOME/bin:$PATH"
fi
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
fx="$root/testdata/library"
sha256sum -c --quiet - <<SUMS
0812f284ac5dd0d617461d9a2ab6ac6811137f25122dfffd4788a4871e732d00  $fx/deps/commons-text-1.9.jar
4ee380259c068d1dbe9e84ab52186f2acd65de067ec09beff731fca1697fdb16  $fx/deps/commons-lang3-3.11.jar
SUMS
java "$root/scripts/JavaBuild.java" "$fx/lib" "$fx/lib.jar" 11 "$fx/deps/commons-text-1.9.jar"
java "$root/scripts/JavaBuild.java" "$fx/client" "$fx/client.jar" 11 "$fx/lib.jar"
cp_list="$fx/client.jar:$fx/lib.jar:$fx/deps/commons-text-1.9.jar:$fx/deps/commons-lang3-3.11.jar"
java "$root/scripts/MethodTrace.java" "$cp_list" fx.Client "$fx/observed.raw" 'lib.*' 'org.apache.commons.text.StringSubstitutor'
{
    echo "# generated by scripts/library-oracle.sh on $(java -version 2>&1 | head -1)"
    echo "# lib.* and StringSubstitutor method bodies that ran on the real JVM (owner#name+desc)"
    grep -v '\$\$Lambda/' "$fx/observed.raw"  # hidden classes: names differ per run
} > "$fx/observed.txt"
rm "$fx/observed.raw"
cat "$fx/observed.txt"
