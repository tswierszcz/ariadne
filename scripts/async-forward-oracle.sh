#!/usr/bin/env bash
# ASYNC_CALLBACKS a3-2 oracle: builds testdata/async-forward/app.jar and
# runs af.Main (a real ThreadPoolExecutor) under scripts/MethodBreakTrace.java,
# writing every af.* method body that ran to observed.txt. No network.
#
# Usage: scripts/async-forward-oracle.sh
set -euo pipefail
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
fx="$root/testdata/async-forward"
java "$root/scripts/JavaBuild.java" "$fx/src" "$fx/app.jar" 11
java "$root/scripts/MethodBreakTrace.java" "$fx/app.jar" af.Main "$fx/observed.raw" af.Api af.Deep af.Main af.Pool af.Relay af.Task af.Unused
{
    echo "# generated by scripts/async-forward-oracle.sh on $(java -version 2>&1 | head -1)"
    echo "# af.* method bodies that ran on the real JVM (owner#name+desc)"
    sort -u "$fx/observed.raw"
} > "$fx/observed.txt"
rm "$fx/observed.raw"
cat "$fx/observed.txt"
