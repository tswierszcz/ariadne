#!/usr/bin/env bash
# ASYNC_CALLBACKS a3-5 oracle: builds testdata/async-listeners/app.jar and
# runs al.Main (a broadcast on a second thread, a real PropertyChangeSupport) under
# scripts/MethodBreakTrace.java, writing every al.* method body that ran to
# observed.txt. No network.
#
# Usage: scripts/async-listeners-oracle.sh
set -euo pipefail
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
fx="$root/testdata/async-listeners"
java "$root/scripts/JavaBuild.java" "$fx/src" "$fx/app.jar" 11
java "$root/scripts/MethodBreakTrace.java" "$fx/app.jar" al.Main "$fx/observed.raw" 'al.*'
{
    echo "# generated by scripts/async-listeners-oracle.sh on $(java -version 2>&1 | head -1)"
    echo "# al.* method bodies that ran on the real JVM (owner#name+desc)"
    LC_ALL=C sort -u "$fx/observed.raw" | grep -v '\$\$Lambda'
} > "$fx/observed.txt"
rm "$fx/observed.raw"
cat "$fx/observed.txt"
