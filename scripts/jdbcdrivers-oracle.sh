#!/usr/bin/env bash
# JDBC drivers oracle (jdbc:drivers). Builds testdata/jdbcdrivers/app.jar
# (fx.app.Main opens jdbc:fx:oracle through DriverManager; fx.drv.FxDriver,
# registered in META-INF/services, accepts it) and runs it with pgjdbc
# 42.2.18 and MySQL Connector/J 8.0.23 ahead of it on the class path, under
# scripts/MethodTrace.java (JDI): every pgjdbc and Connector/J body the JVM
# enters is written to testdata/jdbcdrivers/observed.txt. DriverManager
# offers the URL to both; each checks it and returns null.
# The driver jars (from Maven Central, checked below), app.jar and the file
# are committed; TestJDBCDriversOracle needs no JDK.
#
# Usage: scripts/jdbcdrivers-oracle.sh [JAVA_HOME]
set -euo pipefail
JAVA_HOME_ARG="${1:-${JAVA_HOME:-}}"
if [ -n "$JAVA_HOME_ARG" ]; then
    export JAVA_HOME="$JAVA_HOME_ARG"
    export PATH="$JAVA_HOME/bin:$PATH"
fi
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
fx="$root/testdata/jdbcdrivers"
sha256sum -c --quiet - <<SUMS
0c891979f1eb2fe44432da114d09760b5063dad9e669ac0ac6b0b6bfb91bb3ba  $fx/deps/postgresql-42.2.18.jar
ff7d5b402afd39c12787471505a33a304103b238ec1b7a44e8936d3329da7535  $fx/deps/mysql-connector-java-8.0.23.jar
SUMS
java "$root/scripts/JavaBuild.java" "$fx/app" "$fx/app.jar" 11
cp_list="$fx/deps/postgresql-42.2.18.jar:$fx/deps/mysql-connector-java-8.0.23.jar:$fx/app.jar"
java "$root/scripts/MethodTrace.java" "$cp_list" fx.app.Main "$fx/observed.raw" 'org.postgresql.*' 'com.mysql.*'
{
    echo "# generated by scripts/jdbcdrivers-oracle.sh on $(java -version 2>&1 | head -1)"
    echo "# pgjdbc and Connector/J method bodies that ran on the real JVM (owner#name+desc)"
    grep -v '\$\$Lambda/' "$fx/observed.raw"  # hidden classes: names differ per run
} > "$fx/observed.txt"
rm "$fx/observed.raw"
wc -l "$fx/observed.txt"
